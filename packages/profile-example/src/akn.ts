/**
 * The source, with no engine in sight: where the files are and how to read one. Pure functions,
 * so they are tested without a network (tests/akn.test.ts).
 *
 * The Italian Senate publishes its legislative documents in Akoma Ntoso XML on GitHub
 * (SenatoDellaRepubblica/AkomaNtosoBulkData, CC BY 4.0, legislatures 13-19, refreshed hourly):
 * `Leg<legislature>/Atto<ddl id, 8 digits>/<kind>/<text id>-<suffix>.akn.xml`. The ddl id is the
 * one in the Senate's linked data (`http://dati.senato.it/ddl/<id>`).
 */

export const REPOSITORY = "SenatoDellaRepubblica/AkomaNtosoBulkData";
/** GitHub's documented contents API: a folder listing as JSON (at most 1000 entries). */
export const API_BASE = `https://api.github.com/repos/${REPOSITORY}/contents`;
/** The files themselves. */
export const RAW_BASE = `https://raw.githubusercontent.com/${REPOSITORY}/master`;

export const KINDS = ["ddlpres", "ddlcomm", "ddlmess", "emend", "emendc", "resaula", "sommcomm"] as const;
export type Kind = (typeof KINDS)[number];

export const KIND_TITLES: Record<Kind, string> = {
  ddlpres: "bill as presented",
  ddlcomm: "committee text",
  ddlmess: "bill as passed to the other chamber",
  emend: "amendments in the Assembly",
  emendc: "amendments in committee",
  resaula: "Assembly verbatim reports",
  sommcomm: "committee summary reports"
};

/** GitHub's contents API lists at most this many entries per folder. */
export const LISTING_CAP = 1000;

/** A file name as the repository uses them: an 8-digit text id and a suffix by document type. */
export const FILE_NAME = /^\d{8}-(ft|em|ra|rc)\.akn\.xml$/;

export function billPath(legislature: number, ddl: number, kind?: Kind): string {
  const folder = `Leg${legislature}/Atto${String(ddl).padStart(8, "0")}`;
  return kind ? `${folder}/${kind}` : folder;
}

export const listingUrl = (legislature: number, ddl: number, kind?: Kind) => `${API_BASE}/${billPath(legislature, ddl, kind)}`;
export const fileUrl = (legislature: number, ddl: number, kind: Kind, file: string) => `${RAW_BASE}/${billPath(legislature, ddl, kind)}/${file}`;

/** One entry of a contents API listing, the fields this profile reads. */
export interface ListingEntry {
  name: string;
  type: string;
  size?: number;
  download_url?: string | null;
}

export function isListing(value: unknown): value is ListingEntry[] {
  return Array.isArray(value) && value.every((e) => typeof e === "object" && e !== null && typeof (e as ListingEntry).name === "string");
}

export interface AknSummary {
  /** FRBRname: "Emendamento", "disegno di legge", "resoconto sommario di Commissione". */
  name?: string;
  /** FRBRsubtype: EMEND, DDLPRES, SOMMCOMM, ... */
  subtype?: string;
  /** FRBRnumber: the amendment, bill or report number. */
  number?: string;
  /** FRBRdate, and what the date is ("presentazione"). */
  date?: string;
  dateName?: string;
  /** The document's text after the metadata, tags removed, whitespace collapsed. */
  text: string;
}

const ENTITIES: Record<string, string> = { amp: "&", lt: "<", gt: ">", quot: '"', apos: "'", nbsp: " " };

export function decodeEntities(s: string): string {
  return s.replace(/&(#x[0-9a-f]+|#\d+|[a-z]+);/gi, (whole, ref: string) => {
    if (ref[0] === "#") {
      const code = ref[1] === "x" || ref[1] === "X" ? parseInt(ref.slice(2), 16) : parseInt(ref.slice(1), 10);
      return Number.isFinite(code) && code > 0 && code <= 0x10ffff ? String.fromCodePoint(code) : whole;
    }
    return ENTITIES[ref.toLowerCase()] ?? whole;
  });
}

const attr = (xml: string, element: string, attribute: string): string | undefined => {
  const m = xml.match(new RegExp(`<an:${element}\\b[^>]*\\b${attribute}="([^"]*)"`));
  return m ? decodeEntities(m[1]) : undefined;
};

/**
 * The FRBR metadata of the work and the plain text. A regular-expression reading, not an XML
 * parser: enough for these files, which are generated by one system, and it keeps the profile
 * free of dependencies on Workers.
 */
export function summarize(xml: string): AknSummary {
  const metaEnd = xml.indexOf("</an:meta>");
  const body = metaEnd >= 0 ? xml.slice(metaEnd + "</an:meta>".length) : xml;
  const text = decodeEntities(body.replace(/<[^>]*>/g, " ")).replace(/\s+/g, " ").trim();
  return {
    name: attr(xml, "FRBRname", "value"),
    subtype: attr(xml, "FRBRsubtype", "value"),
    number: attr(xml, "FRBRnumber", "value"),
    date: attr(xml, "FRBRdate", "date"),
    dateName: attr(xml, "FRBRdate", "name"),
    text
  };
}
